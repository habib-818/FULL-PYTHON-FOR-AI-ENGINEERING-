## WHAT IS A LIST?
"""
 A List stores multiple items in order
"""
fruits = ["apple", "banana", "orange"]
print(fruits)


# Access Elements
print(fruits[0])

# Modify a List
fruits[1] = "mango"
print(fruits)



## LIST METHODS
"""
 * append()      -> Add one item
 * extend()      -> Add multiple items
 * insert()      -> Insert at a position
 * remove()      -> Remove by value
 * pop()         -> Remove by index (default: last)
 * clear()       -> Remove all items
 * index()       -> Find index of an item
 * count()       -> Count occurrences
 * sort()        -> Sort the list
 * reverse()     -> Reverse the list
 * copy()        -> Copy the list
"""

## BUILTIN FUNCTION IN PYTHON 
"""
 * len()         -> Number of items
 * max()         -> Largest item
 * min()         -> Smallest item
 * sum()         -> Sum of numbers
 * sorted()      -> Return a new sorted list
"""