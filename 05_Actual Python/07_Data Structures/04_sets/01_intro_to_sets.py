## WHAT IS SETS?
"""
 A set is an unordered, mutable collection of UNIQUE items.
"""

## EXAMPLE
"""
numbers = {1, 2, 3, 4}

Empty Set: my_set = set()
"""

## SET OPERATIONS
A = {1, 2, 3}
B = {3, 4, 5}


# 1. union()

A.union(B)

A | B



# 2. intersection()

A.intersection(B)

A & B




# 3. difference()

A.difference(B)

A - B

# 4. symmetric_difference()

A.symmetric_difference(B)

A ^ B
