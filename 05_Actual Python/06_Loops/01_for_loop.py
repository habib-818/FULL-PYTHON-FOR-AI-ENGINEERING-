## WHAT IS FOR LOOP?
"""
 A for loop in Python is used to repeat a block of code for each item in a sequence, 
 such as a list, string, tuple, or a range of numbers.
"""

# 01: Print numbers 0 through 4
for i in range(5):
    print(i)

# 02: Loop Through a List
fruits = ["apple", "banana", "orange"]

for fruit in fruits:
    print(fruit)

# 03: Loop Through a String
word = "Python"

for letter in word:
    print(letter)


